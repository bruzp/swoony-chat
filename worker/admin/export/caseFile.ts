import fontkit from "@pdf-lib/fontkit";
import { FINGERPRINT_HOW_TO } from "@shared/legal/canonical";
import { messageCount, type LegalRecords } from "@shared/legal/records";
import { formatPht, formatUtc } from "@shared/legal/time";
import fontDataUrl from "dejavu-fonts-ttf/ttf/DejaVuSans.ttf?inline";
import { PDFDocument, rgb, type PDFFont, type PDFPage } from "pdf-lib";

export interface CaseFileInput {
  caseRef: string;
  generatedAt: number;
  generatedBy: string;
  scope: string;
  records: LegalRecords;
  fingerprint: string;
}

type LineStyle = "title" | "heading" | "body" | "gap";

export interface CaseFileLine {
  text: string;
  style: LineStyle;
}

const A4: [number, number] = [595.28, 841.89];
const MARGIN = 48;
const FOOTER_Y = 28;
const STYLE_SIZE: Record<LineStyle, number> = { title: 16, heading: 12, body: 9, gap: 6 };
const LINE_GAP = 1.35;
const TEXT_COLOR = rgb(0.1, 0.1, 0.12);
const MUTED_COLOR = rgb(0.4, 0.4, 0.45);
const TAB_OR_NEWLINE = /[\t\n\r]/g;

let fontBytes: Uint8Array | null = null;

function embeddedFontBytes(): Uint8Array {
  if (!fontBytes) {
    const base64 = fontDataUrl.slice(fontDataUrl.indexOf(",") + 1);
    fontBytes = Uint8Array.from(atob(base64), (char) => char.charCodeAt(0));
  }
  return fontBytes;
}

function codePointLabel(codePoint: number): string {
  return `U+${codePoint.toString(16).toUpperCase().padStart(4, "0")}`;
}

export function drawableText(text: string, canDraw: (codePoint: number) => boolean): string {
  let out = "";
  for (const char of text.replace(TAB_OR_NEWLINE, " ")) {
    const codePoint = char.codePointAt(0) ?? 0;
    const isControl = codePoint < 0x20 || (codePoint >= 0x7f && codePoint < 0xa0);
    out += !isControl && canDraw(codePoint) ? char : codePointLabel(codePoint);
  }
  return out;
}

function plural(count: number, word: string): string {
  return `${String(count)} ${word}${count === 1 ? "" : "s"}`;
}

function bothTimes(at: number | null): string {
  return at === null ? "still open" : `${formatPht(at)} (${formatUtc(at)})`;
}

export function caseFileLines(
  input: CaseFileInput,
  canDraw: (codePoint: number) => boolean,
): CaseFileLine[] {
  const { records } = input;
  const lines: CaseFileLine[] = [];
  const add = (text: string, style: LineStyle = "body") => {
    lines.push({ text: drawableText(text, canDraw), style });
  };
  const gap = () => lines.push({ text: "", style: "gap" });

  add("Swoony case file", "title");
  add(`Case reference: ${input.caseRef}`);
  add(`Generated: ${bothTimes(input.generatedAt)}`);
  add(`Generated by: ${input.generatedBy}`);
  add(`Search: ${input.scope}`);
  add(
    `Records: ${plural(records.connections.length, "connection")}, ${plural(records.chats.length, "chat")}, ` +
      `${plural(records.content.length, "saved chat")} (${plural(messageCount(records), "message")})`,
  );
  add("Times are Philippine time (PHT, UTC+8) with UTC in brackets.");

  gap();
  add("Connections", "heading");
  if (records.connections.length === 0) add("None.");
  for (const connection of records.connections) {
    const detected = connection.detectedCountry ?? "unknown";
    add(
      `User ${connection.userId} · nickname ${connection.nickname} · IP ${connection.ip} · ` +
        `country ${connection.country} (detected ${detected})`,
    );
    add(`   joined ${bothTimes(connection.joinedAt)}, left ${bothTimes(connection.leftAt)}`);
  }

  gap();
  add("Chats", "heading");
  if (records.chats.length === 0) add("None.");
  for (const chat of records.chats) {
    add(`Chat ${chat.chatId} · between ${chat.userA} and ${chat.userB}`);
    add(`   started ${bothTimes(chat.startedAt)}, ended ${bothTimes(chat.endedAt)}`);
  }

  gap();
  add("Saved messages", "heading");
  if (records.content.length === 0) add("None.");
  for (const entry of records.content) {
    gap();
    const reason = entry.reason ? `, reason ${entry.reason}` : "";
    add(`Chat ${entry.chatId} · ${entry.kind}${reason} · saved ${bothTimes(entry.createdAt)}`);
    for (const message of entry.messages) {
      add(`[${formatPht(message.sentAt)}] ${message.from}: ${message.text}`);
    }
  }

  gap();
  add(`Records fingerprint (SHA-256): ${input.fingerprint}`);
  add(`How to recompute: ${FINGERPRINT_HOW_TO}`);
  return lines;
}

export function wrapText(text: string, measure: (text: string) => number, width: number): string[] {
  if (text === "") return [""];
  const space = measure(" ");
  const rows: string[] = [];
  let row = "";
  let rowWidth = 0;
  for (const word of text.split(" ")) {
    const wordWidth = measure(word);
    const joinedWidth = row ? rowWidth + space + wordWidth : wordWidth;
    if (joinedWidth <= width) {
      row = row ? `${row} ${word}` : word;
      rowWidth = joinedWidth;
      continue;
    }
    if (row) rows.push(row);
    if (wordWidth <= width) {
      row = word;
      rowWidth = wordWidth;
      continue;
    }
    row = "";
    rowWidth = 0;
    for (const char of word) {
      const charWidth = measure(char);
      if (rowWidth + charWidth <= width) {
        row += char;
        rowWidth += charWidth;
      } else {
        rows.push(row);
        row = char;
        rowWidth = charWidth;
      }
    }
  }
  rows.push(row);
  return rows;
}

function drawFooters(pages: PDFPage[], font: PDFFont, caseRef: string): void {
  pages.forEach((page, index) => {
    const label = `${caseRef} · Page ${String(index + 1)} of ${String(pages.length)}`;
    const size = 8;
    const x = A4[0] - MARGIN - font.widthOfTextAtSize(label, size);
    page.drawText(label, { x, y: FOOTER_Y, size, font, color: MUTED_COLOR });
  });
}

export async function renderCaseFile(input: CaseFileInput): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  pdf.registerFontkit(fontkit);
  const font = await pdf.embedFont(embeddedFontBytes(), { subset: true });
  const charset = new Set(font.getCharacterSet());
  const caseRef = drawableText(input.caseRef, (codePoint) => charset.has(codePoint));
  pdf.setTitle(`Swoony case file ${input.caseRef}`);
  pdf.setSubject(`Records fingerprint ${input.fingerprint}`);
  pdf.setAuthor(input.generatedBy);
  pdf.setCreator("Swoony");
  pdf.setProducer("Swoony");
  pdf.setCreationDate(new Date(input.generatedAt));
  pdf.setModificationDate(new Date(input.generatedAt));

  const textWidth = A4[0] - MARGIN * 2;
  const pages: PDFPage[] = [];
  let page = pdf.addPage(A4);
  pages.push(page);
  let y = A4[1] - MARGIN;
  for (const line of caseFileLines(input, (codePoint) => charset.has(codePoint))) {
    const size = STYLE_SIZE[line.style];
    const measure = (text: string) => font.widthOfTextAtSize(text, size);
    for (const row of wrapText(line.text, measure, textWidth)) {
      const height = size * LINE_GAP;
      if (y - height < MARGIN) {
        page = pdf.addPage(A4);
        pages.push(page);
        y = A4[1] - MARGIN;
      }
      y -= height;
      if (row) page.drawText(row, { x: MARGIN, y, size, font, color: TEXT_COLOR });
    }
  }
  drawFooters(pages, font, caseRef);
  return pdf.save({ useObjectStreams: false });
}
