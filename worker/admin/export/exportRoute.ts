import { LIMITS } from "@shared/config";
import { canonicalRecordsJson, FINGERPRINT_HOW_TO } from "@shared/legal/canonical";
import { chatsCsv, connectionsCsv, messagesCsv } from "@shared/legal/csv";
import { messageCount, type LegalQuery, type LegalRecords } from "@shared/legal/records";
import { formatPht, formatUtc, utcDate } from "@shared/legal/time";
import {
  caseRefForFileName,
  EXPORT_PARTS_HEADER,
  EXPORT_SHA256_HEADER,
} from "@shared/protocol/admin";
import { strToU8, zipSync } from "fflate";
import { z } from "zod";
import { sha256BytesHex, sha256Hex } from "../../support/hash";
import { chatIdSchema, lookupSchema, lookupTarget, type ActionTarget } from "../actions";
import { recordAction } from "../auditRecorder";
import { fail, readCaseRef, type WebRoute } from "../webRoute";
import { renderCaseFile } from "./caseFile";

const exportSchema = z.object({
  format: z.enum(["csv", "pdf"]),
  scope: z.union([
    z.object({ query: lookupSchema }),
    z.object({ chatId: chatIdSchema, part: z.number().int().min(1).max(100_000).optional() }),
  ]),
});

type ExportScope = z.infer<typeof exportSchema>["scope"];

const CONTENT_TYPES = { csv: "application/zip", pdf: "application/pdf" } as const;
const EXTENSIONS = { csv: "zip", pdf: "pdf" } as const;

function scopeTarget(scope: ExportScope): ActionTarget {
  return "chatId" in scope ? { kind: "chat", value: scope.chatId } : lookupTarget(scope.query);
}

function describeQuery(query: LegalQuery): string {
  const who =
    query.userId !== undefined
      ? `User ID ${query.userId}`
      : query.nickname !== undefined
        ? `Nickname ${query.nickname}`
        : "All activity";
  return `${who}, ${formatPht(query.from)} to ${formatPht(query.to)}`;
}

function describeScope(scope: ExportScope, parts: number): string {
  if (!("chatId" in scope)) return describeQuery(scope.query);
  const part = parts > 1 ? `, part ${String(scope.part ?? 1)} of ${String(parts)}` : "";
  return `Saved chat ${scope.chatId}${part}`;
}

function isTooLarge(records: LegalRecords): boolean {
  const rows = records.connections.length + records.chats.length;
  return messageCount(records) > LIMITS.exportMaxMessages || rows > LIMITS.exportMaxRows;
}

function recordCount(records: LegalRecords): number {
  return records.connections.length + records.chats.length + records.content.length;
}

interface ExportFile {
  caseRef: string;
  generatedAt: number;
  generatedBy: string;
  scope: string;
  records: LegalRecords;
  fingerprint: string;
}

function csvZip(file: ExportFile): Uint8Array<ArrayBuffer> {
  const summary = [
    `Case reference: ${file.caseRef}`,
    `Generated: ${formatPht(file.generatedAt)} (${formatUtc(file.generatedAt)})`,
    `Generated by: ${file.generatedBy}`,
    `Search: ${file.scope}`,
    `Records fingerprint (SHA-256): ${file.fingerprint}`,
    `How to recompute: ${FINGERPRINT_HOW_TO}`,
    "",
  ].join("\r\n");
  const mtime = new Date(file.generatedAt);
  return zipSync(
    {
      "connections.csv": strToU8(connectionsCsv(file.records.connections)),
      "chats.csv": strToU8(chatsCsv(file.records.chats)),
      "messages.csv": strToU8(messagesCsv(file.records.content)),
      "fingerprint.txt": strToU8(summary),
    },
    { mtime },
  );
}

async function pdfBytes(file: ExportFile): Promise<Uint8Array<ArrayBuffer>> {
  const bytes = await renderCaseFile(file);
  return new Uint8Array(bytes);
}

export const exportRoute: WebRoute = async ({ request, deps, body, actor }) => {
  const caseRef = readCaseRef(body);
  if (caseRef === null) return fail({ error: "invalid_case_ref" }, 400);
  const parsed = exportSchema.safeParse(body);
  if (!parsed.success) return fail({ error: "invalid_request" }, 400);
  const { format, scope } = parsed.data;
  const { truncated, parts, ...records } =
    "chatId" in scope
      ? { ...(await deps.retention.chatRecords(scope.chatId, scope.part)), truncated: false }
      : { ...(await deps.retention.lookup(scope.query)), parts: 1 };
  const part = "chatId" in scope ? (scope.part ?? 1) : 1;
  if (part > parts) return fail({ error: "invalid_request" }, 400);
  if (truncated || isTooLarge(records)) return fail({ error: "export_too_large" }, 413);

  const generatedAt = deps.now();
  const file: ExportFile = {
    caseRef,
    generatedAt,
    generatedBy: actor,
    scope: describeScope(scope, parts),
    records,
    fingerprint: await sha256Hex(canonicalRecordsJson(records)),
  };
  const bytes = format === "pdf" ? await pdfBytes(file) : csvZip(file);
  const fileHash = await sha256BytesHex(bytes);
  await recordAction(deps, request, {
    actor,
    action: "export",
    caseRef,
    result: { status: 200, body: null, target: scopeTarget(scope), count: recordCount(records) },
    exportSha256: fileHash,
  });
  const fileName = `${caseRefForFileName(caseRef)}-${utcDate(generatedAt)}.${EXTENSIONS[format]}`;
  return new Response(bytes, {
    headers: {
      "Content-Type": CONTENT_TYPES[format],
      "Content-Disposition": `attachment; filename="${fileName}"`,
      "Cache-Control": "no-store",
      [EXPORT_SHA256_HEADER]: fileHash,
      [EXPORT_PARTS_HEADER]: String(parts),
    },
  });
};
