import type { LegalRecords } from "@shared/legal/records";
import { PDFDocument } from "pdf-lib";
import { describe, expect, it } from "vitest";
import {
  caseFileLines,
  drawableText,
  renderCaseFile,
  wrapText,
  type CaseFileInput,
} from "./caseFile";

const SAVED_CHAT: LegalRecords["content"][number] = {
  chatId: "c".repeat(64),
  kind: "report_snapshot",
  reason: "harassment",
  createdAt: Date.UTC(2026, 10, 1, 6),
  messages: [{ from: "u-1", text: "hello 😀 world", sentAt: Date.UTC(2026, 10, 1, 5, 30) }],
};

const RECORDS: LegalRecords = {
  connections: [
    {
      userId: "u-1",
      nickname: "Mika",
      ip: "203.0.113.9",
      country: "PH",
      detectedCountry: "PH",
      joinedAt: Date.UTC(2026, 10, 1, 4),
      leftAt: null,
    },
  ],
  chats: [
    {
      chatId: "c".repeat(64),
      userA: "u-1",
      userB: "u-2",
      startedAt: Date.UTC(2026, 10, 1, 5),
      endedAt: Date.UTC(2026, 10, 1, 6),
    },
  ],
  content: [SAVED_CHAT],
};

function input(records: LegalRecords = RECORDS): CaseFileInput {
  return {
    caseRef: "NBI-2026/1142",
    generatedAt: Date.UTC(2026, 10, 19, 12),
    generatedBy: "owner@example.com",
    scope: "User ID u-1, 2026-11-01 to 2026-11-02",
    records,
    fingerprint: "f".repeat(64),
  };
}

const latinOnly = (codePoint: number) => codePoint < 0x2000;

describe("caseFileLines", () => {
  it("starts with the case reference, times, author and record counts", () => {
    const text = caseFileLines(input(), latinOnly)
      .map((line) => line.text)
      .join("\n");
    expect(text).toContain("Case reference: NBI-2026/1142");
    expect(text).toContain("2026-11-19 20:00:00 PHT (2026-11-19T12:00:00.000Z)");
    expect(text).toContain("Generated by: owner@example.com");
    expect(text).toContain("1 connection, 1 chat, 1 saved chat (1 message)");
    expect(text).toContain("203.0.113.9");
  });

  it("ends with the records fingerprint and how to recompute it", () => {
    const lines = caseFileLines(input(), latinOnly).map((line) => line.text);
    const tail = lines.slice(-3).join("\n");
    expect(tail).toContain(`Records fingerprint (SHA-256): ${"f".repeat(64)}`);
    expect(tail).toContain("keys sorted");
  });

  it("replaces characters the font cannot draw with their code point", () => {
    const text = caseFileLines(input(), latinOnly)
      .map((line) => line.text)
      .join("\n");
    expect(text).toContain("hello U+1F600 world");
  });
});

describe("drawableText", () => {
  it("keeps drawable text and turns control characters into code points", () => {
    expect(drawableText("a\u0007b", () => true)).toBe("aU+0007b");
    expect(drawableText("tab\there", () => true)).toBe("tab here");
  });
});

describe("renderCaseFile", () => {
  it("renders an A4 PDF with the case reference in its properties", async () => {
    const bytes = await renderCaseFile(input());
    expect(new TextDecoder().decode(bytes.slice(0, 5))).toBe("%PDF-");
    const pdf = await PDFDocument.load(bytes);
    expect(pdf.getTitle()).toContain("NBI-2026/1142");
    expect(pdf.getSubject()).toContain("f".repeat(64));
    const { width, height } = pdf.getPage(0).getSize();
    expect([Math.round(width), Math.round(height)]).toEqual([595, 842]);
  });

  it("spreads long chats over several pages without throwing on emoji", async () => {
    const many: LegalRecords = {
      ...RECORDS,
      content: [
        {
          ...SAVED_CHAT,
          messages: Array.from({ length: 300 }, (_, i) => ({
            from: "u-1",
            text: `message ${String(i)} with emoji 🎉 and Ñandú and Привет`,
            sentAt: Date.UTC(2026, 10, 1, 5) + i,
          })),
        },
      ],
    };
    const pdf = await PDFDocument.load(await renderCaseFile(input(many)));
    expect(pdf.getPageCount()).toBeGreaterThan(3);
  });
});

describe("wrapText", () => {
  const charWidth = (text: string) => text.length;

  it("wraps on spaces and breaks long words", () => {
    expect(wrapText("aa bb cc", charWidth, 5)).toEqual(["aa bb", "cc"]);
    expect(wrapText("abcdefgh", charWidth, 3)).toEqual(["abc", "def", "gh"]);
    expect(wrapText("", charWidth, 3)).toEqual([""]);
  });

  it("measures each word and character only once, so long text stays fast", () => {
    let calls = 0;
    const counting = (text: string) => {
      calls++;
      return text.length;
    };
    const text = `${"word ".repeat(200)}${"x".repeat(1000)}`;
    wrapText(text, counting, 80);
    expect(calls).toBeLessThan(1300);
  });

  it("embeds only the glyphs it uses, so a small case file stays small", async () => {
    const bytes = await renderCaseFile(input());
    expect(bytes.byteLength).toBeLessThan(200_000);
    const pdf = await PDFDocument.load(bytes);
    expect(pdf.getPageCount()).toBeGreaterThan(0);
  });
});
